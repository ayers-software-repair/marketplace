// Computes art/lancelot-icon.svg: the Lancelot wordmark in Pacifico, red with a cream outline, on the
// LanceDB mark's lavender-to-coral field. Pacifico (SIL Open Font License 1.1, art/fonts/) is the
// lettering of the owner's reference. The SVG is generated output; edit the tokens here and run
// `node art/lancelot-icon.mjs`, then render the PNG with a browser that has the font (the @font-face
// below points at art/fonts/Pacifico-Regular.ttf, relative to the SVG).
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SIZE = 1024;
const CORNER = 200;
const FIELD = ["#e7d2f6", "#ff734a"]; // bottom-left, top-right: the LanceDB favicon field
const RED = "#d8322b";
const OUTLINE = "#fff6ee";
// Measured in Chromium: this size sets "Lancelot" in Pacifico to 94% of the width, outline included.
const FONT_SIZE = 260;
const OUTLINE_WIDTH = 0.14; // em
const TILT = -4; // degrees, the reference's rise to the right

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}" viewBox="0 0 ${SIZE} ${SIZE}">
  <!-- Generated by art/lancelot-icon.mjs. Edit that file, not this one. -->
  <defs>
    <style>
      @font-face { font-family: "Pacifico"; src: url("fonts/Pacifico-Regular.ttf") format("truetype"); }
      text { font-family: "Pacifico"; font-size: ${FONT_SIZE}px; fill: ${RED}; stroke: ${OUTLINE}; stroke-width: ${OUTLINE_WIDTH}em; stroke-linejoin: round; stroke-linecap: round; paint-order: stroke; }
    </style>
    <linearGradient id="field" x1="0" y1="1" x2="1" y2="0">
      <stop offset="0" stop-color="${FIELD[0]}"/>
      <stop offset="1" stop-color="${FIELD[1]}"/>
    </linearGradient>
  </defs>
  <rect width="${SIZE}" height="${SIZE}" rx="${CORNER}" fill="url(#field)"/>
  <text x="${SIZE / 2}" y="${SIZE / 2}" text-anchor="middle" dominant-baseline="central" transform="rotate(${TILT} ${SIZE / 2} ${SIZE / 2})">Lancelot</text>
</svg>
`;

const out = join(dirname(fileURLToPath(import.meta.url)), "lancelot-icon.svg");
writeFileSync(out, svg);
console.log(`wrote ${out}`);
