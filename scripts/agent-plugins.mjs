#!/usr/bin/env node
// Writes the Agent Plugins root files (plugin.json, mcp.json) for each plugin
// from its .claude-plugin manifest. Spec: https://agent-plugins.org/specification
// Usage: node scripts/agent-plugins.mjs [--check]
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const SCHEMA = "https://agent-plugins.org/schemas/1.0.0/";
// The spec's plugin.json is a closed schema, so the host goes in the description.
const HOST = {
  tldr: "Runs in Claude Code only; it uses Claude Code hook modules.",
  "letterstream-mail": "Needs the Claude in Chrome extension, so it runs in Claude Code today.",
  lancelot: "Runs in any MCP client over stdio.",
};
const readJson = (p) => JSON.parse(readFileSync(p, "utf8"));
const market = readJson(join(root, ".claude-plugin/marketplace.json"));
const out = [];

for (const name of readdirSync(join(root, "plugins")).sort()) {
  const dir = join(root, "plugins", name);
  const src = readJson(join(dir, ".claude-plugin/plugin.json"));
  const tags = market.plugins.find((p) => p.name === src.name)?.tags;
  const manifest = { $schema: SCHEMA + "plugin.schema.json", name: src.name, version: src.version };
  manifest.description = [src.description, HOST[name]].filter(Boolean).join(" ");
  manifest.author = { name: src.author.name };
  manifest.repository = src.repository;
  manifest.license = src.license;
  if (tags) manifest.keywords = tags;
  out.push([join(dir, "plugin.json"), manifest]);

  const note = ["Generated by scripts/agent-plugins.mjs from .claude-plugin; do not edit plugin.json or mcp.json here."];
  const mcpPath = join(dir, ".mcp.json");
  if (existsSync(mcpPath)) {
    const servers = {};
    const dropped = [];
    for (const [id, s] of Object.entries(readJson(mcpPath).mcpServers)) {
      servers[id] = { type: "stdio", command: s.command, args: s.args };
      dropped.push(...Object.keys(s.env ?? {}));
    }
    out.push([join(dir, "mcp.json"), { $schema: SCHEMA + "mcp.schema.json", mcpServers: servers }]);
    // The spec has no user configuration and expands only PLUGIN_ROOT and PLUGIN_DATA.
    if (dropped.length)
      note.push(`mcp.json carries no env: the spec has no user configuration. Pass ${dropped.join(" and ")} to the server through your client's own settings.`);
  }
  out.push([join(dir, "GENERATED.md"), note.join("\n\n") + "\n"]);
}

let stale = 0;
for (const [path, data] of out) {
  const text = typeof data === "string" ? data : JSON.stringify(data, null, 2) + "\n";
  const same = existsSync(path) && readFileSync(path, "utf8") === text;
  if (same) continue;
  if (check) { console.error(`would change: ${path}`); stale++; } else writeFileSync(path, text);
}
process.exit(stale ? 1 : 0);
